CREATE TABLE REQUEST_LOG (
    ID BIGSERIAL PRIMARY KEY,
    CLIENT_ID BIGINT,
    CLIENT_NAME VARCHAR(150),
    API_CODE VARCHAR(100) NOT NULL,
    ENDPOINT VARCHAR(1000) NOT NULL,
    METHOD VARCHAR(10) NOT NULL,
    STATUS_CODE INTEGER NOT NULL,
    DURATION_MS BIGINT NOT NULL,
    REQUESTED_AT TIMESTAMPTZ NOT NULL
);

CREATE INDEX IDX_REQUEST_LOG_CLIENT_ID ON REQUEST_LOG (CLIENT_ID);
CREATE INDEX IDX_REQUEST_LOG_API_CODE ON REQUEST_LOG (API_CODE);
CREATE INDEX IDX_REQUEST_LOG_STATUS_CODE ON REQUEST_LOG (STATUS_CODE);
CREATE INDEX IDX_REQUEST_LOG_REQUESTED_AT ON REQUEST_LOG (REQUESTED_AT DESC);