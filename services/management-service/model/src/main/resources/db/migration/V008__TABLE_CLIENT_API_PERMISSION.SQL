CREATE TABLE CLIENT_API_PERMISSION (
    X_PERMISSION_ID BIGSERIAL PRIMARY KEY,

    X_CLIENT_ID BIGINT NOT NULL,
    X_API_ID BIGINT NOT NULL,

    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PERMISSION_CLIENT
        FOREIGN KEY (X_CLIENT_ID)
        REFERENCES CLIENT(X_CLIENT_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_PERMISSION_API
        FOREIGN KEY (X_API_ID)
        REFERENCES API(X_API_ID)
        ON DELETE CASCADE,

    CONSTRAINT UK_PERMISSION_CLIENT_API
        UNIQUE (X_CLIENT_ID, X_API_ID)
);